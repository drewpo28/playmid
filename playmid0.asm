; =============== Информационное сообщение ================================
; Вызывается при запуске программы без параметров. Выводит в терминал встроенный хелп.

sub_20B5:
                ld      hl, txt_20BEh   ; HL указывает на текстовую строку (см. ниже)
                push    hl              ; Передача адреса строки через стек
                call    sub_2950        ; Системная функция печати строки (аналог printf / print string)
                pop     af              ; Очистка стека
                ret

; ---------------------------------------------------------------------------
txt_20BEh       db  " PLAYMID file.mid", 0Dh, 0Dh
				db  "Plays a MIDI format 0 file thru", 0Dh
                db  "MIDI OUT connector.", 0Dh, 0
                
; ---------------------------------------------------------------------------
; Этот блок отвечает за первичную загрузку заголовка файла (MIDI Header) в память по адресу byte_3000.

loc_2106:
                call    sub_2A37        ; Вход в функцию, создание фрейма
                push    af
                push    af
                ld      hl, 200h        ; Размер буфера чтения / лимит (512 байт)
                push    hl
                ld      hl, byte_3000   ; Адрес в ОЗУ, куда читать заголовок файла
                push    hl
                ld      a, (ix+4)       ; Идентификатор (хэндл) открытого файла
                push    af
                inc     sp
                call    sub_2A70        ; Функция чтения данных из файла (например, DOS_READ)
                pop     af
                inc     sp
                ld      hl, txt_27FCh
                ex      (sp), hl
                ld      hl, byte_3000   ; Сверяем или обрабатываем прочитанное по адресу byte_3000
                push    hl
                call    sub_2851        ; Проверка сигнатуры файла (ищет заголовок "MThd")
                pop     af
                pop     af
                ld      c, l
                ld      a, h
                or      c
                jr      nz, loc_213A    ; Если заголовок корректен — идем дальше к `loc_213A`
                
                ; Если файл поврежден или это не MIDI:
                ld      hl, txt_2801h   ; Адрес строки об ошибке "Not a MIDI file"
                push    hl
                call    sub_2950        ; Вывод ошибки на экран
                pop     af
                jp      loc_27F7        ; Переход на экстренный выход

; -------------- Проверка формата ---------------------------------------------------
; В спецификации MIDI заголовок по смещению +9 хранит тип формата (Format Type: 0, 1 или 2). Программа читает байт из адреса #3009.

loc_213A:
                ld      a, (byte_3009)  ; Читаем байт формата файла (в буфере #3000 это смещение +9)
                ld      (byte_2B01), a  ; Сохраняем тип формата в глобальную переменную
                ld      a, (byte_2B01)
                or      a               ; Проверка: Формат == 0?
                jr      z, loc_2151     ; Если Format 0 — все отлично, продолжаем к `loc_2151`
                
                ; Если формат файла 1 или 2 (программа их не поддерживает):
                ld      hl, txt_2816h   ; Адрес строки с ошибкой "Only Format 0 supported"
                push    hl
                call    sub_2950        ; Вывод сообщения
                pop     af
                jp      loc_27F7        ; Выход из программы

; -------------- Чтение временного разрешения MIDI (Division) и его конвертация ------------
; В заголовке MIDI-файла по адресу #300C и #300D хранится 16-битное число division (количество тиков на четвертную ноту).

loc_2151:
                ld      a, (byte_300C)
                ld      b, a
                ld      c, 0
                ld      a, (byte_300D)
                ld      e, a
                ld      d, 0
                ; --- Сборка и выравнивание байт (из Big-Endian в Little-Endian) ---
                ld      a, c
                or      e
                ld      c, a
                ld      a, b
                or      d
                ld      b, a            ; BC = собранное 16-битное значение division
                
                ; --- Сохранение значения в переменную по адресу 2B08h (32-битное число) ---
                ld      hl, word_2B08
                ld      (hl), c         ; Младший байт
                ld      a, b
                inc     hl
                ld      (hl), a         ; Второй байт
                rla                     ; Проверка знака (7-й бит) для расширения до 32 бит
                sbc     a, a            ; Если 7-й бит был 1, то A = #FF, иначе A = #00
                inc     hl
                ld      (hl), a         ; Третий байт
                inc     hl
                ld      (hl), a         ; Старший байт
                
                ; --- Проверка типа времени (Ticks per Quarter Note vs SMPTE) ---
                ld      a, (byte_300C)
                rlca                    ; Сдвигаем старший бит (бит 15 исходного слова) во флаг переноса (C)
                jr      nc, loc_21B1    ; Если бит 15 == 0 -> это стандартные тики на четверть (Переход к loc_21B1)
                
                ; --- Блок для SMPTE формата времени (редкий случай для MIDI) ---
                ld      bc, byte_300C
                ld      a, (byte_300C)
                res     7, a            ; Сбрасываем старший бит
                ld      (bc), a
                ld      a, (byte_300D)
                ld      c, a
                ld      b, 0
                ld      l, c
                ld      h, b
                ; Серия команд 'ADD HL, HL' и 'ADD HL, BC' выполняет быстрое умножение значения на 500+
                add     hl, hl
                add     hl, hl
                add     hl, bc
                add     hl, hl
                add     hl, hl
                add     hl, hl
                add     hl, hl
                add     hl, hl
                add     hl, hl
                add     hl, hl
                add     hl, hl
                ex      de, hl
                ld      a, (byte_300C)
                ld      c, a
                ld      b, 0
                push    bc
                push    de
                call    sub_2A95        ; Математическая подпрограмма (деление/умножение)
                pop     af
                pop     af
                ; Результат работы sub_2A95 сохраняется как 32-битное значение темпа по адресу 2B14h
                ld      c, l
                ld      b, h
                ld      hl, byte_2B14
                ld      (hl), c
                ld      a, b
                inc     hl
                ld      (hl), a
                rla
                sbc     a, a
                inc     hl
                ld      (hl), a
                inc     hl
                ld      (hl), a
                jr      loc_21E7        ; Переход к следующему этапу

; -------------- Расчет темпа для стандартного формата ------------------
; Если формат времени стандартный (большинство MIDI-файлов), программа рассчитывает 
; длительность одного тика на основе дефолтного темпа (500,000 микросекунд на четверть = 120 BPM).

loc_21B1:
                ld      hl, (word_2B0A) ; Загрузка старшего слова division
                push    hl
                ld      hl, (word_2B08) ; Загрузка младшего слова division
                push    hl
                ld      hl, 0
                push    hl
                ld      hl, 500h        ; Передача константы 500 (часть от 500,000 мкс дефолтного темпа)
                push    hl
                call    sub_2BBA        ; Вызов функции деления (500000 / division)
                ; Очистка стека от 4-х аргументов (8 байт)
                pop     af
                pop     af
                pop     af
                pop     af
                ld      c, l
                ld      b, h            ; BC = результат деления
                
                ; Подготовка аргументов для следующей математической функции (длинное 32-битное умножение)
                ld      hl, 0
                push    hl
                ld      hl, 1F4h        ; Константа 500 (1F4h)
                push    hl
                push    de
                push    bc
                call    sub_2B28        ; sub_2B28 производит финальный расчет тиков в микросекундах
                pop     af
                pop     af
                pop     af
                pop     af
                ld      c, l
                ld      b, h            ; DE:BC = 32-битный результат (микросекунд на один MIDI-тик)
                
                ; Сохранение полученного значения времени в переменную по адресу 2B14h (4 байта)
                ld      hl, byte_2B14
                ld      (hl), c         ; 1-й байт
                inc     hl
                ld      (hl), b         ; 2-й байт
                inc     hl
                ld      (hl), e         ; 3-й байт
                inc     hl
                ld      (hl), d         ; 4-й байт

; -------------- Проверка сигнатуры трека "MTrk" (loc_21E7:) ------------------------------------
; Cразу за заголовком MIDI файла (MThd) обязан идти заголовок первого трека — MTrk (адрес буфера #300E).

loc_21E7:
                ld      hl, txt_2837h   ; Указатель на эталонную строку "MTrk" в ПЗУ/ОЗУ плеера
                push    hl
                ld      hl, byte_300E   ; Адрес в буфере, где ожидается сигнатура трека
                push    hl
                call    sub_2851        ; Функция сравнения строк (аналог strcmp)
                pop     af
                pop     af
                ld      c, l
                ld      a, h
                or      c               ; Проверка результата: HL == 0?
                jr      nz, loc_2204    ; Если строки совпали (сигнатура "MTrk" найдена) -> идем дальше
                
                ; Если сигнатура не совпала (файл поврежден):
                ld      hl, txt_283Ch   ; Указатель на текст ошибки "Track marker not found"
                push    hl
                call    sub_2950        ; Печать ошибки
                pop     af
                jp      loc_27F7        ; Выход из программы

; -------------- Инициализация указателей потока ------------------------------------
;Сброс глобальных игровых переменных и индексов буфера перед стартом проигрывания.

loc_2204:
                ld      hl, word_2B1C
                ld      (hl), 16h       ; Инициализация указателя смещения в буфере данных (начинаем с 22-го байта, где идут ноты)
                inc     hl
                ld      (hl), 0
                ld      hl, byte_2B1E
                ld      (hl), 0
                inc     hl
                ld      (hl), 2         ; Старший байт текущего смещения чтения
                xor     a
                ld      hl, byte_2B18   ; Обнуление 32-битного счетчика прошедшего времени (адреса byte_2B18..2B1Bh)
                ld      (hl), a
                inc     hl
                ld      (hl), a
                inc     hl
                ld      (hl), a
                inc     hl
                ld      (hl), a
                ld      hl, byte_2B07
                ld      (hl), 0         ; Сброс флага "Конец трека"

;---------------  Главный цикл: опрос клавиатуры на выход -----------------

loc_2224:
                ld      a, 7Fh          ; Сканирование полуряда клавиш SPACE - SYMBOL SHIFT
                in      a, (0FEh)       ; Чтение порта клавиатуры Spectrum
                rrca                    ; Проверка нажатия клавиши SPACE (Пробел)
                jp      nc, loc_27F7    ; Если SPACE нажат (флаг C = 0) -> мгновенное прерывание и выход в DOS
                jr      loc_2231        ; Если нет — продолжаем выполнение
                jp      loc_27F7        ; Выход из программы
                
; ------------- Двойная буферизация потока данных -----------------------------
; Этот блок управляет подгрузкой данных с диска/карты памяти. Используются два кольцевых буфера по адресам byte_3000 и #3200. 
; Если указатель переходит границу текущего буфера, вызывается чтение следующего сектора

loc_2231:
                ld      c, 0
                ld      a, (word_2B1C+1)
                and     2
                ld      b, a
                ld      e, 0
                ld      a, (byte_2B1F)
                and     2
                ld      d, a
                ld      a, c
                sub     e
                jr      nz, loc_2249    ; Проверка: нужно ли сменить активную страницу буфера памяти?
                ld      a, b
                sub     d
                jr      z, loc_2283    ; Если буфер еще полон — пропускаем чтение и идем к loc_2283

loc_2249:
                ld      a, b
                or      c
                jr      z, loc_2262     ; Условие выбора первого буфера
                
                ; --- Подгрузка новой порции данных в буфер byte_3000 ---
                ld      hl, 200h        ; Читать 512 байт (1 сектор)
                push    hl
                ld      hl, byte_3000   ; Адрес назначения
                push    hl
                ld      a, (ix+4)       ; Хэндл файла
                push    af
                inc     sp
                call    sub_2A70        ; Чтение с диска
                pop     af
                pop     af
                inc     sp
                jr      loc_2275         ; Переход к обновлению указателей

loc_2262:
                ; --- Подгрузка новой порции данных в альтернативный буфер #3200 ---
                ld      hl, 200h
                push    hl
                ld      hl, byte_3200       ; Адрес назначения
                push    hl
                ld      a, (ix+4)
                push    af
                inc     sp
                call    sub_2A70        ; Чтение с диска
                pop     af
                pop     af
                inc     sp

loc_2275:
                ; Синхронизация текущих адресов чтения
                push    hl
                ld      a, (word_2B1C)
                ld      (byte_2B1E), a
                ld      a, (word_2B1C+1)
                ld      (byte_2B1F), a
                pop     hl

; --------------- Чтение текущего байта MIDI-события ------

loc_2283:
                xor     a               ; Обнуление временной переменной дельта-времени события
                ld      hl, byte_2B0C
                ld      (hl), a
                inc     hl
                ld      (hl), a
                inc     hl
                ld      (hl), a
                inc     hl
                ld      (hl), a

; ------------- Декодирование VLQ (Дельта-времени) -------------------
; В формате MIDI дельта-время упаковано по 7 бит в байт. Если старший бит байта (бит 7) равен 1, 
; это значит, что число продолжается в следующем байте. Код организует цикл накопления:

loc_228E:
                ld      a, 0
                ld      hl, word_2B1C       ; HL = указатель на текущее смещение в буфере нот
                add     a, (hl)
                ld      c, a
                ld      a, 30h          ; Базовый адрес сегмента памяти (byte_3000)
                inc     hl
                adc     a, (hl)         ; Добавляем смещение с учетом переносa
                ld      b, a            ; BC теперь содержит точный физический адрес байта в ОЗУ (#30xx или #32xx)
                
                ld      a, (bc)         ; Читаем байт MIDI-команды или дельта-времени из буфера
                ld      (byte_2B03), a  ; Сохраняем прочитанный байт в переменную текущего события
                
                ; Инкремент указателя буфера (сдвиг вперед на 1 байт для следующего шага)
                ld      bc, (word_2B1C)
                inc     bc
                ld      hl, word_2B1C
                ld      (hl), c         ; Сохраняем обновленный адрес
                
                ld      a, b
                and     3
                inc     hl
                ld      (hl), a
                
                ld      hl, byte_2B0C
                ld      c, (hl)
                inc     hl
                ld      b, (hl)
                inc     hl
                ld      e, (hl)
                inc     hl
                ld      d, (hl)
                ld      a, 7

loc_22B8:
                sla     c               ; Младший байт влево, старший бит уходит во флаг переноса (C)
                rl      b               ; Протаскиваем перенос через остальные байты
                rl      e
                rl      d
                dec     a
