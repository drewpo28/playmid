; -Главная инициализация программы.-------------------------------------------
START:
                xor     a               ; Обнуление аккумулятора (A = 0)
                ld      (byte_2B00), a  ; Запись 0 в статусную переменную
                push    hl              ; Сохранение указателя на параметры (командную строку)
                call    sub_2013        ; Вызов основного тела программы
                inc     sp              ; Коррекция стека после вызова (очистка 2 байт)
                inc     sp
                ld      iy, 5C3Ah       ; Стандартное восстановление системной переменной ERR_NR/FLAGS для ZX Spectrum
                ld      a, l            ; L содержит результат выполнения функции
                or      a               ; Проверка: L == 0?
                ret     z               ; Если 0 — успешный выход в систему
                scf                     ; Если не 0 — устанавливаем флаг переноса (сигнал ошибки)
                ret                     ; Выход

; =============== S U B R O U T I N E =======================================
; Здесь происходит парсинг аргументов командной строки и инициализация музыкального чипа AY.

sub_2013:
                call    sub_2A37        ; Инициализация фрейма стека (внутри sub_2A37 скрыт `POP HL / PUSH IX / LD IX, SP`)
                dec     sp              ; Выделение 1 байта в стеке под локальную переменную
                
                ; --- Работа с музыкальным чипом AY-3-8912 ---
                ld      a, AY_IOPORT_A  ; Выбор регистра 14 (Reg E - Управление портами ввода-вывода)
                ld      bc, AY_REG      ; Выбор порта AY-чипа на Spectrum 128
                out     (c), a          ; Посылаем номер регистра
                ld      a, 0FEh         ; Маска для настройки линий порта
                ld      bc, AY_DATA     ; Порт записи данных AY
                out     (c), a          ; Запись маски
                halt                    ; Ожидание прерывания (синхронизация)
                
                ld      (ix-001h), 0FFh ; Запись флага во временную ячейку в стеке
                ld      hl, 0
                add     hl, sp          ; HL указывает на текущую вершину стека
                ex      de, hl          ; DE = указатель на буфер в стеке
                ld      a, 1
                push    af              ; Передача аргумента "1" через стек
                inc     sp              ; (выравнивание стека под 1 байт)
                push    de              ; Передача адреса буфера
                call    sub_28A1        ; Скорее всего, функция парсинга аргументов (парсит строку в буфер)
                pop     af              ; Очистка стека
                inc     sp
                
                ld      a, (ix+5)       ; Проверка аргументов командной строки (адреса переданного имени файла)
                or      (ix+4)          ; Если (IX+4) и (IX+5) оба равны 0 (файл не указан)
                jr      nz, loc_2048    ; Если файл указан -> переходим к открытию файла `loc_2048`
                
                call    sub_20B5        ; Если файл НЕ указан -> выводим текст-хелп ("PLAYMIDI file.mid...")
                ld      l, 0            ; Код возврата = 0
                jr      loc_206B        ; Переход к выходу

; ---------------------------------------------------------------------------
; Если пользователь передал имя файла в командной строке, управление передается сюда:

loc_2048:
                ld      l, (ix+4)       ; HL = указатель на имя файла,
                ld      h, (ix+5)       ; взятый из параметров функции
                push    hl              ; Передаем указатель в стек
                call    sub_206F        ; Вызов функции открытия и обработки MIDI-файла
                pop     af              ; Очистка стека
                ld      c, l            ; Сохранение результата работы в C
                halt                    ; Синхронизация по кадровому прерыванию
                
                ; ... Повторный вызов системной функции sub_28A1 (вероятно, закрытие дескрипторов/освобождение памяти)
                ld      (ix-001h), 0FFh
                ld      hl, 0
                add     hl, sp
                ex      de, hl
                push    bc
                ld      a, 1
                push    af
                inc     sp
                push    de
                call    sub_28A1
                pop     af
                inc     sp
                pop     bc
                ld      l, c            ; Возвращаем сохраненный ранее результат работы программы в L

loc_206B:
                inc     sp              ; Освобождаем локальный байт стека
                pop     ix              ; Восстанавливаем IX вызывающей функции
                ret


; =============== S U B R O U T I N E =======================================

sub_206F:
                call    sub_2A37
                ld      hl, 0FFE0h
                add     hl, sp
                ld      sp, hl
                ld      hl, 0
                add     hl, sp
                ex      de, hl
                ld      c, e
                ld      b, d
                push    de
                push    bc
                ld      l, (ix+4)
                ld      h, (ix+5)
                push    hl
                call    sub_292A
                pop     af
                pop     af
                pop     de
                ld      a, 1
                push    af
                inc     sp
                push    de
                call    sub_2A41
                pop     af
                inc     sp
                ld      b, l
                ld      a, b
