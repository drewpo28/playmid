                ld      de, 0           ; Обнуляем регистры остатка (DE:BC = 0)
                ld      (ix-001h), 20h  ; Записываем счетчик цикла: 32 итерации (20h в hex = 32)


loc_2B3B:
                ld      a, (ix+7)       ; Читаем самый старший байт Делимого
                rlc     a               ; Сдвигаем циклически влево, чтобы проверить бит 7
                and     1               ; Изолируем этот бит (0 или 1)
                ld      l, a            ; Временно сохраняем этот бит в L
                
