                ld      a, b : sbc a, (ix+9) : ld b, a
                ld      a, e : sbc a, (ix+0Ah) : ld e, a
                ld      a, d : sbc a, (ix+0Bh) : ld d, a ; Регистры DE:BC теперь хранят новый остаток
                
                ; --- Установка бита частного в младшем байте Делимого ---
                ld      a, (ix+4)
                or      1               ; Помечаем, что деление в этом разряде успешно (младший бит = 1)
                ld      (ix+4), a
                
                ; Пустые Си-загрузки "сами в себя" (артефакт работы компилятора, не меняющий данные)
                ld      a, (ix+5) : ld (ix+5), a
                ld      a, (ix+6) : ld (ix+6), a
                ld      a, (ix+7) : ld (ix+7), a

loc_2BA1:
                dec     (ix-001h)       ; Уменьшаем счетчик 32-битного цикла
                ld      a, (ix-001h)
                or      a               ; Проверяем, дошел ли счетчик до 0?
                jr      nz, loc_2B3B    ; Если нет -> возвращаемся на loc_2B3B и обрабатываем следующий бит
                
                ; --- Финал: Сборка результата ---
                ; Цикл завершен. Исходное делимое в стеке (IX+4..IX+7) за 32 шага сдвигов 
                ; и логических `OR 1` полностью превратилось в итоговое Частное.
                ld      l, (ix+4)
                ld      h, (ix+5)       ; HL = младшие 16 бит Частного
                ld      e, (ix+6)
                ld      d, (ix+7)       ; DE = старшие 16 бит Частного
                
                inc     sp              ; Освобождаем локальный байт счетчика из стека
                pop     ix              ; Восстанавливаем родительский IX
                ret                     ; Возврат. Результат деления возвращается в DE:HL


