; =============== Перевод байта в HEX-символы ==============================
; Эта функция принимает байт (IX+4) и адрес буфера (IX+5, IX+6). Она делит байт на две 
; тетрады (по 4 бита), каждую тетраду превращает в символ '0'..'9' или 'A'..'F' и записывает в память.

sub_29B0:
