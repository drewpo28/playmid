                inc     hl
                ld      h, (hl)
                ld      l, a            ; HL = младшее слово второго числа ($Y_{low}$)
                
                ; --- Вызов 16-битного умножения ---
                push    bc              ; Сохраняем указатели
                push    hl              ; Передаем $Y_{low}$
                push    de              ; Передаем $X_{low}$
                call    sub_2A95        ; HL = $X_{low} \cdot Y_{low}$
                pop     af : pop af     ; Очистка стека от параметров
                
                ex      de, hl          ; Переносим результат первого умножения в DE
                pop     bc              ; Восстанавливаем BC
                
                ; --- Сохранение младшей части результата ---
                ld      l, (ix-002h)
                ld      h, (ix-001h)    ; Извлекаем адрес ячейки
                ld      (hl), e
                inc     hl
                ld      (hl), d         ; Записали первые 16 бит итогового произведения

                ld      e, c
                ld      d, b
                inc     de
                inc     de
                inc     sp
                inc     sp
                push    de              ; Манипуляции со стеком для выравнивания
                
                ld      l, c
                ld      h, b
                inc     hl : inc hl
                ld      e, (hl)
                inc     hl
                ld      d, (hl)         ; DE = снова загружаем $X_{low}$
                
                ld      l, (ix-005h)
                ld      h, (ix-004h)
                inc     hl : inc hl
                ld      a, (hl)
                ld      (ix-002h), a
                inc     hl
                ld      a, (hl)
                ld      (ix-001h), a    ; (IX-2) = теперь содержит $Y_{high}$ (старшее слово 2-го числа)
                
                ld      l, c
                ld      h, b
                ld      a, (hl)
                inc     hl
                ld      h, (hl)
                ld      l, a            ; HL = вспомогательное значение
                
                ; --- Вызов второго умножения ---
                push    bc
                push    de              ; Передаем $X_{low}$
                push    hl
                ld      l, (ix-002h)
                ld      h, (ix-001h)
                push    hl              ; Передаем $Y_{high}$
                call    sub_2A95        ; HL = $X_{low} :cdot Y_{high}$
                pop     af : pop af : pop de : pop bc ; Очистка стека

                add     hl, de          ; Складываем перенос и текущее частичное произведение
                ex      de, hl          ; Результат накопления — в DE
                pop     hl              ; Восстанавливаем указатель буфера из стека
                push    hl
                ld      (hl), e
                inc     hl
                ld      (hl), d         ; Сохраняем обновленную старшую часть результата в стек-фрейм

                ld      e, c
                ld      d, b
                inc     de : inc de
                ld      (ix-003h), e
                ld      (ix-002h), d    ; Фиксация временных адресов
                
                ld      l, c
                ld      h, b
                inc     hl : inc hl
                ld      e, (hl)
                inc     hl
                ld      d, (hl)         
                
                ld      l, c
                ld      h, b
                inc     hl
                ld      a, (hl)
                ld      (ix-001h), a    ; Извлечение $X_{high}$ в (IX-1)
                
                ld      l, (ix-005h)
                ld      h, (ix-004h)
                inc     hl
                ld      h, (hl)         ; Подготовка $Y_{low}$
                
                push    de
                push    bc
                ld      e, (ix-001h)    ; E = $X_{high}$
                ld      l, 0
                ld      d, l            ; D = 0
                ld      b, 8            ; B = 8 (подготовка к побитовому сдвигу / сложению)


loc_2C66:
