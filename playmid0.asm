                ld      sp, hl          ; Зафиксировали новую вершину стека
                
                ; Настройка внутренних указателей буфера стека
                ld      hl, 0Bh
                add     hl, sp          
                ld      c, l
                ld      b, h            ; BC = базовый адрес локальной памяти на стеке
                ld      e, c
                ld      d, b
                inc     de
                inc     de              ; DE = BC + 2 (указатель на ячейку промежуточного результата)
                
                ld      (ix-002h), e
                ld      (ix-001h), d    ; Спасаем адрес этой ячейки в локальные переменные фрейма (IX-2)

                ld      l, c
                ld      h, b
                inc     hl
                inc     hl              ; Смещение к аргументу в стеке
                ld      e, (hl)
                inc     hl
                ld      d, (hl)         ; DE = младшее слово первого числа ($X_{low}$)
                
                ld      hl, 0Fh
                add     hl, sp
                ld      (ix-005h), l
                ld      (ix-004h), h    ; Запоминаем адрес в (IX-5)
                
