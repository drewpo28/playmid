                rlca : rlca : rlca : rlca ; Четыре циклических сдвига влево меняют тетрады местами
                and     0Fh             ; Маскируем, оставляя бывшую старшую тетраду
                ld      c, a            ; C = значение старшей тетрады (0..15)
                
                ld      e, (ix+5)
                ld      d, (ix+6)       ; DE = восстанавливаем базовый адрес буфера
                ld      b, c
                ld      a, 9
