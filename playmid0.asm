                sla     (ix+4)          ; Младший байт влево, бит 7 уходит в Carry
                rl      (ix+5)          ; Протаскиваем перенос через остальные байты...
                rl      (ix+6)
                rl      (ix+7)          ; ...до самого старшего байта
                
