                jr      z, loc_2B61     ; Если 0 — пропускаем
                set     0, c            ; Если 1 — устанавливаем бит 0 в регистре C (младший бит DE:BC)

loc_2B61:

                ld      a, c
                sub     (ix+8)          ; Вычитаем младший байт
                ld      a, b
                sbc     a, (ix+9)       ; Каскадное вычитание с переносом (SBC)
                ld      a, e
                sbc     a, (ix+0Ah)
                ld      a, d
                sbc     a, (ix+0Bh)     ; Вычитаем старший байт
                
                jr      c, loc_2BA1     ; Если Carry = 1 -> результат отрицательный (Делитель больше Остатка).
                                        ; Вычитать нельзя! Прыгаем на loc_2BA1 (остаток не восстанавливаем).

                ; --- Физическое вычитание Делителя из Остатка ---
